export interface Theme {
  dark: boolean;
  color: {
    background: string;
    surface: string;
    surfaceRaised: string;
    border: string;
    text: string;
    textMuted: string;
    textInverse: string;
    primary: string;
    primaryPressed: string;
    onPrimary: string;
    success: string;
    successSoft: string;
    danger: string;
    dangerSoft: string;
    info: string;
    infoSoft: string;
    /** Behind a modal or an offer card. */
    scrim: string;
  };
  radius: { sm: number; md: number; lg: number; xl: number; pill: number };
  space: (n: number) => number;
  font: {
    /** Body copy. */
    body: number;
    small: number;
    caption: number;
    /** A fare, a total -- the number the user came to see. */
    display: number;
    title: number;
    heading: number;
  };
}

