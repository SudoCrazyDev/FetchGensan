/** Status colours for a job badge. */
export function statusTone(
  status: string,
): 'neutral' | 'progress' | 'success' | 'danger' | 'attention' {
  switch (status) {
    case 'completed':
      return 'success';
    case 'cancelled':
    case 'expired':
      return 'danger';
    case 'awaiting_approval':
      return 'attention';
    case 'draft':
      return 'neutral';
    default:
      return 'progress';
  }
}
